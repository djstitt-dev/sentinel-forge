"""Portable offline enrollment artifact construction and validation."""

from __future__ import annotations
import hashlib, json, tarfile, tempfile
from pathlib import Path, PurePosixPath
from typing import Any
from .enrollment import EnrollmentBundle, EnrollmentError, verify_bundle
from .secure_io import ensure_private_file

FORMAT="sentinel-courier-enrollment-artifact-v1"
MAX_ARTIFACT_BYTES=5*1024*1024
FILES=("bundle.json","install.py","README.txt")

INSTALLER='''#!/usr/bin/env python3
"""Sentinel Courier enrollment installer stub.

This portable installer validates local package structure only. It intentionally
does not configure networking, services, credentials, SSH, Conduit, or activation.
Use the reviewed Sentinel enrollment library for controlled installation.
"""
import json, pathlib, sys
root=pathlib.Path(__file__).resolve().parent
manifest=json.loads((root/"bundle.json").read_text())
required={"protocol","enrollment_id","forge_identity","remote_identity","remote_role",
          "permitted_actions","permitted_target","policy_reference","one_time","payload_digest"}
missing=required-set(manifest)
if missing:
    raise SystemExit("invalid enrollment bundle: missing "+",".join(sorted(missing)))
print("Enrollment package structurally readable for:",manifest["remote_identity"])
print("No installation or network activation performed.")
'''

README='''Sentinel Courier Enrollment Package

This package was generated by Sentinel Forge for offline review and controlled
installation on the exact remote identity named in bundle.json.

IMPORTANT:
- Validate package integrity before installation.
- Installation does not itself authorize activation.
- Do not reuse this package for another host.
- This package contains no production credential or private key.
- Network/service activation requires a separately reviewed implementation and
  explicit operator approval.
'''

def export_artifact(bundle:EnrollmentBundle, destination:Path)->Path:
    if not verify_bundle(bundle): raise EnrollmentError("cannot export invalid enrollment bundle")
    destination=Path(destination)
    destination.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory() as td:
        root=Path(td)
        (root/"bundle.json").write_bytes(_canonical(bundle.as_dict()))
        (root/"install.py").write_text(INSTALLER,encoding="utf-8")
        (root/"README.txt").write_text(README,encoding="utf-8")
        manifest={"format":FORMAT,"enrollment_id":bundle.enrollment_id,
                  "remote_identity":bundle.remote_identity,"files":{}}
        for name in FILES:
            raw=(root/name).read_bytes()
            manifest["files"][name]={"size":len(raw),"sha256":hashlib.sha256(raw).hexdigest()}
        (root/"MANIFEST.json").write_bytes(_canonical(manifest))
        # Deterministic tar metadata. Uncompressed tar avoids gzip timestamp variance.
        ensure_private_file(destination)
        with tarfile.open(destination,"w",format=tarfile.PAX_FORMAT) as tf:
            for name in ("MANIFEST.json",)+FILES:
                info=tf.gettarinfo(str(root/name),arcname=name)
                info.uid=0; info.gid=0; info.uname=""; info.gname=""; info.mtime=0
                info.mode=0o755 if name=="install.py" else 0o600
                with (root/name).open("rb") as fh: tf.addfile(info,fh)
    return destination

def validate_artifact(path:Path, *, expected_remote_identity:str|None=None)->dict[str,Any]:
    path=Path(path)
    try:
        st=path.stat()
        if not path.is_file(): raise EnrollmentError("enrollment artifact must be a regular file")
        if st.st_size > MAX_ARTIFACT_BYTES: raise EnrollmentError("enrollment artifact exceeds 5 MiB bound")
        with tarfile.open(path,"r") as tf:
            members=tf.getmembers()
            names=[m.name for m in members]
            expected=["MANIFEST.json",*FILES]
            if names != expected: raise EnrollmentError("artifact member set/order is invalid")
            for m in members:
                p=PurePosixPath(m.name)
                if p.is_absolute() or ".." in p.parts or not m.isfile():
                    raise EnrollmentError("unsafe artifact member")
                if m.size > 1024*1024: raise EnrollmentError("artifact member exceeds 1 MiB bound")
            raw={m.name:tf.extractfile(m).read() for m in members}
    except (OSError,tarfile.TarError) as exc:
        raise EnrollmentError("cannot read enrollment artifact") from exc
    try:
        manifest=json.loads(raw["MANIFEST.json"])
        bundle=json.loads(raw["bundle.json"])
    except (json.JSONDecodeError,UnicodeDecodeError) as exc:
        raise EnrollmentError("malformed artifact JSON") from exc
    if manifest.get("format")!=FORMAT: raise EnrollmentError("wrong enrollment artifact format")
    if manifest.get("enrollment_id")!=bundle.get("enrollment_id"):
        raise EnrollmentError("artifact enrollment identity mismatch")
    if manifest.get("remote_identity")!=bundle.get("remote_identity"):
        raise EnrollmentError("artifact remote identity mismatch")
    if expected_remote_identity is not None and bundle.get("remote_identity")!=expected_remote_identity:
        raise EnrollmentError("artifact is bound to another remote host")
    for name in FILES:
        spec=manifest.get("files",{}).get(name)
        if not isinstance(spec,dict): raise EnrollmentError("artifact manifest missing file identity")
        if spec.get("size")!=len(raw[name]) or spec.get("sha256")!=hashlib.sha256(raw[name]).hexdigest():
            raise EnrollmentError("artifact file integrity failure")
    return {"format":FORMAT,"enrollment_id":bundle["enrollment_id"],
            "remote_identity":bundle["remote_identity"],"validated":True}

def _canonical(value:Any)->bytes:
    return (json.dumps(value,sort_keys=True,separators=(",",":"))+"\n").encode()
